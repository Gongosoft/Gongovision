import type { PaletteLut, PaletteStop } from '@/types/gongoizer.d.ts';

type PaletteStops = readonly PaletteStop[];

const LUT_STEPS = 128;

function fromStops(stops: PaletteStops): PaletteLut {
	const out = new Uint8Array(LUT_STEPS * 3);
	for (let i = 0; i < LUT_STEPS; i++) {
		const x = i / LUT_STEPS;
		let k = stops.length - 1;
		for (let j = 0; j < stops.length; j++) {
			if (stops[j]![0] <= x) {
				k = j;
			}
		}
		const a = stops[k]!;
		const b = stops[(k + 1) % stops.length]!;
		const span = (b[0] - a[0] + 1) % 1 || 1;
		const f = ((x - a[0] + 1) % 1) / span;
		const e = f * f * (3 - 2 * f);
		out[i * 3] = Math.round(a[1] + (b[1] - a[1]) * e);
		out[i * 3 + 1] = Math.round(a[2] + (b[2] - a[2]) * e);
		out[i * 3 + 2] = Math.round(a[3] + (b[3] - a[3]) * e);
	}
	return out;
}

